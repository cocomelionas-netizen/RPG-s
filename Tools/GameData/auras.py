"""Generates Assets/_Project/Scripts/Editor/AuraData.cs from the source game's client data.

    python3 -I Tools/GameData/auras.py <path to the source data checkout>

Every spell of spell_template with an aura text (aura_description: what a buff or debuff on a unit means, "Stunned.",
"Reduces fire resistance."), by spell name (the first spell of a name wins): the scene builder puts them into
Resources/StatusInfo.asset, which the unit frames show when the pointer is over an effect's icon. The source game's
own name is replaced by "the island".
"""
import os
import re
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import names  # noqa: E402


def game_name(root):
    """The source game's name, read from its executable's file name (so it is never written here)."""
    return next(f[:-4] for f in os.listdir(os.path.join(root, 'bin')) if f.endswith('.exe'))


def cs(text):
    # Every name and text written goes through this project's names (names.py).
    text = names.rename(text)
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main(root):
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Assets', '_Project', 'Scripts', 'Editor', 'AuraData.cs')
    db = sqlite3.connect(os.path.join(root, 'game.db'))
    name = game_name(root)
    auras = {}
    for spell, text in db.execute("select name, aura_description from spell_template where aura_description is not null "
                                  "and trim(aura_description) != '' order by entry"):
        spell = (spell or '').strip()
        if not spell or spell in auras:
            continue
        text = re.sub(r'\b' + name + r'\b', 'the island', ' '.join(text.split()), flags=re.I)
        auras[spell] = text
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by Tools/GameData/auras.py from the source game\'s game.db (spell_template.aura_description):\n')
        f.write('// what each buff or debuff means, by spell name.\n')
        f.write('using System.Collections.Generic;\n\nnamespace RPG.EditorTools\n{\n    internal static class AuraData\n    {\n')
        f.write('        public static readonly Dictionary<string, string> Descriptions = new Dictionary<string, string>\n        {\n')
        for spell, text in auras.items():
            f.write(f'            {{ {cs(spell)}, {cs(text)} }},\n')
        f.write('        };\n    }\n}\n')
    print(f'auras: {len(auras)}')


if __name__ == '__main__':
    main(sys.argv[1])
