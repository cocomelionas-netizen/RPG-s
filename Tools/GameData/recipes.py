"""Generates Assets/_Project/Scripts/Editor/RecipeData.cs from the source game's client data.

Usage: python3 -I Tools/GameData/recipes.py <path to the client data clone> > Assets/_Project/Scripts/Editor/RecipeData.cs

Every crafting recipe (crafting_recipes): the result, how many, and the items it takes (by name). The scene builder keeps
the recipes whose items all exist in this project.
"""
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import names as game_names  # noqa: E402

db = sqlite3.connect(os.path.join(sys.argv[1], 'game.db'))
db.row_factory = sqlite3.Row
names = {row['entry']: row['name'] for row in db.execute('select entry, name from item_template')}


def cs(text):
    # Every name and text written goes through this project's names (names.py).
    text = game_names.rename(text)
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


out = []
w = out.append
w('// Generated by Tools/GameData/recipes.py from the source game\'s game.db (crafting_recipes). Do not edit by hand.')
w('namespace RPG.EditorTools')
w('{')
w('    internal static class RecipeData')
w('    {')
w('        /// <summary>Recipes: result name, how many it makes, and the items it takes (name, count).</summary>')
w('        public static readonly (string result, int count, (string item, int count)[] ingredients)[] All =')
w('        {')
for row in db.execute('select * from crafting_recipes order by entry'):
    ingredients = []
    for i in range(1, 6):
        item = row[f'item{i}']
        if item:
            ingredients.append(f'({cs(names[item])}, {row[f"item{i}_count"] or 1})')
    w(f'            ({cs(names[row["result_item"]])}, {row["result_count"] or 1}, new[] {{ {", ".join(ingredients)} }}),')
w('        };')
w('    }')
w('}')
print('\n'.join(out))
