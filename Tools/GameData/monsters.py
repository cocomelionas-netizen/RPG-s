"""Generates Assets/_Project/Scripts/Editor/MonsterData.cs from the source game's client data.

    python3 -I Tools/GameData/monsters.py <path to the source data checkout>

- The source game's name of every monster spot of StartAreaData.Monsters (same order; matched by cell and the name in
  its comment against npc + npc_template).
- Junk loot like the source game's npc_models_junkloot: each monster model drops some kinds of junk ("Hoof", "Insect
  Scale"); every kind exists for item levels 1-25, its first word giving the level ("Bizarre Hoof" 1 ... "Noteworthy
  Hoof" 25) and its sell price growing with it. Kinds by monster name, for the world and the dungeons.
"""
import collections
import os
import re
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import names  # noqa: E402
import island  # noqa: E402


def cs(text):
    # Every name and text written goes through this project's names (names.py).
    text = names.rename(text)
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main(root):
    here = os.path.dirname(__file__)
    editor = os.path.join(here, '..', '..', 'Assets', '_Project', 'Scripts', 'Editor')
    db = sqlite3.connect(os.path.join(root, 'game.db'))
    q = lambda sql, *a: db.execute(sql, a).fetchall()

    junk_entries = {r[0] for r in q('select distinct item_entry from npc_models_junkloot')}
    rows = q('select entry, name, item_level, sell_price, stack_count from item_template')
    junk = [r for r in rows if r[0] in junk_entries]
    adjectives = {}
    for entry, name, level, sell, stack in junk:
        adjectives.setdefault(int(level), collections.Counter())[name.split()[0]] += 1
    adjective_of = {level: counter.most_common(1)[0][0] for level, counter in adjectives.items()}

    kinds = {}   # kind name -> {level: (full name, sell, stack)}
    kind_of_entry = {}
    for entry, name, level, sell, stack in junk:
        first, _, rest = name.partition(' ')
        kind = rest if first == adjective_of.get(int(level)) and rest else name
        kinds.setdefault(kind, {})[int(level)] = (name, int(round(float(sell))), int(stack or 1))
        kind_of_entry[entry] = kind
    kind_names = sorted(kinds)
    index = {k: i for i, k in enumerate(kind_names)}

    model_kinds = collections.defaultdict(set)
    for model, entry in q('select model_id, item_entry from npc_models_junkloot'):
        if entry in kind_of_entry:
            model_kinds[model].add(index[kind_of_entry[entry]])
    by_name = {}
    for name, model in q('select name, model_id from npc_template'):
        name = (name or '').strip()
        if name and model in model_kinds and name not in by_name:
            by_name[name] = sorted(model_kinds[model])

    source = open(os.path.join(editor, 'StartAreaData.cs')).read()
    start = source.index('Monsters =')
    end = source.index('};', start)
    spots = re.findall(r'\(new Vector3Int\((\d+), (\d+), 0\), \d+, (?:true|false), [\d.]+f\), // (.+)', source[start:end])
    npc_cells = {}
    wanders = {}
    for x, y, name, movement in q('select n.position_x, n.position_y, t.name, n.movement_type from npc n '
                                  'join npc_template t on t.entry = n.entry where n.map = 1'):
        cell = island.cell_of(x, y)
        npc_cells.setdefault(cell, []).append(name.strip())
        wanders.setdefault((cell, name.strip()), movement == 1)
    spot_names, spot_wanders = [], []
    for cx, cy, name in spots:
        name = name.strip()
        if name not in npc_cells.get((int(cx), int(cy)), []):
            print(f'warning: no {name} at {cx},{cy}', file=sys.stderr)
        spot_names.append(name)
        spot_wanders.append(wanders.get(((int(cx), int(cy)), name), True))
    # Faction 2: neutral, fights only when attacked; a mechanic immunity mask: not stunned, incapacitated or rooted.
    passive = sorted({n.strip() for (n,) in q('select name from npc_template where faction = 2')})
    immune = sorted({n.strip() for (n,) in q('select name from npc_template where mechanic_immune_mask <> 0')})

    with open(os.path.join(editor, 'MonsterData.cs'), 'w', newline='\n') as f:
        f.write("// Generated by Tools/GameData/monsters.py from the source game's game.db (npc, npc_template, npc_models_junkloot,\n")
        f.write('// item_template): monster names and their junk loot.\n')
        f.write('namespace RPG.EditorTools\n{\n    internal static class MonsterData\n    {\n')
        f.write('        /// <summary>The source game\'s name of each monster spot, in StartAreaData.Monsters order.</summary>\n')
        f.write('        public static readonly string[] SpotNames =\n        {\n')
        for name in spot_names:
            f.write(f'            {cs(name)},\n')
        f.write('        };\n\n')
        f.write('        /// <summary>Whether each monster spot wanders (npc.movement_type 1) or stands still, in SpotNames order.</summary>\n')
        f.write('        public static readonly bool[] SpotWanders =\n        {\n')
        for start in range(0, len(spot_wanders), 16):
            f.write('            ' + ' '.join(('true,' if w else 'false,') for w in spot_wanders[start:start + 16]) + '\n')
        f.write('        };\n\n')
        f.write('        /// <summary>Neutral monsters (npc_template faction 2): they fight only when attacked.</summary>\n')
        f.write('        public static readonly string[] Passive =\n        {\n')
        for name in passive:
            f.write(f'            {cs(name)},\n')
        f.write('        };\n\n')
        f.write('        /// <summary>Monsters with a mechanic immunity (mostly bosses): no stuns, incapacitates or roots.</summary>\n')
        f.write('        public static readonly string[] ControlImmune =\n        {\n')
        for name in immune:
            f.write(f'            {cs(name)},\n')
        f.write('        };\n\n')
        f.write('        /// <summary>Kinds of junk: for item levels 1-25 the full name, sell price and stack size.</summary>\n')
        f.write('        public static readonly (string kind, (string name, int sell, int stack)[] levels)[] Junk =\n        {\n')
        for kind in kind_names:
            levels = kinds[kind]
            entries = ', '.join(f'({cs(levels[l][0])}, {levels[l][1]}, {levels[l][2]})' for l in range(1, 26) if l in levels)
            f.write(f'            ({cs(kind)}, new[] {{ {entries} }}),\n')
        f.write('        };\n\n')
        f.write('        /// <summary>The kinds of junk (indices into Junk) each monster drops, by its source name.</summary>\n')
        f.write('        public static readonly (string monster, int[] junk)[] JunkByMonster =\n        {\n')
        for name in sorted(by_name):
            f.write(f'            ({cs(name)}, new[] {{ {", ".join(map(str, by_name[name]))} }}),\n')
        f.write('        };\n    }\n}\n')
    print(f'{len(spot_names)} spots, {len(kind_names)} junk kinds, {len(by_name)} monsters with junk')


if __name__ == '__main__':
    main(sys.argv[1])
