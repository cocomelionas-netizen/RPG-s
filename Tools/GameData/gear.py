"""Generates Assets/_Project/Scripts/Editor/GearSourceData.cs from the source game's client data.

    python3 -I Tools/GameData/gear.py <path to the source data checkout>

The source game's generated gear (item_template, generated = 1) in its plain quality: for every equip slot and armor
type (armor), weapon type and material (weapons) or neither (necklaces, belts, rings, shields), and every level 1-25,
the base name and the sell price. The scene builder names and prices its gear from these.
Equip types: 1 helm, 2 necklace, 3 chest, 4 belt, 5 legs, 6 feet, 7 hands, 8 ring, 9 weapon, 10 shield, 11 ranged.
"""
import os
import sqlite3
import sys

# Weapon types this project's classes use: 4 swords (warrior), 2 bows (ranger), 5 staves (mage).
WEAPON_TYPES = (2, 4, 5)


def main(root):
    db = sqlite3.connect(os.path.join(root, 'game.db'))
    rows = db.execute(
        'select equip_type, armor_type, weapon_type, weapon_material, required_level, name, sell_price from item_template '
        'where generated = 1 and quality = 2 order by equip_type, armor_type, weapon_type, weapon_material, required_level').fetchall()
    out = os.path.join(os.path.dirname(__file__), '..', '..', 'Assets', '_Project', 'Scripts', 'Editor', 'GearSourceData.cs')
    pieces = []
    for equip, armor, weapon, material, level, name, sell in rows:
        number = lambda v: int(v) if str(v).strip() not in ('', 'None') else 0
        equip, armor, weapon, material = number(equip), number(armor), number(weapon), number(material)
        if equip in (9, 11):
            if weapon not in WEAPON_TYPES:
                continue
            key = material
        elif equip in (2, 4, 8, 10):
            key = 0
        else:
            key = armor
        pieces.append((equip, weapon, key, int(level), name.strip(), round(float(sell), 2)))
    with open(out, 'w', newline='\n') as f:
        f.write("// Generated by Tools/GameData/gear.py from the source game's game.db (item_template, its generated plain gear).\n")
        f.write('namespace RPG.EditorTools\n{\n    internal static class GearSourceData\n    {\n')
        f.write('        /// <summary>\n')
        f.write('        /// Plain gear: equip type (1 helm, 2 necklace, 3 chest, 4 belt, 5 legs, 6 feet, 7 hands, 8 ring, 9 weapon,\n')
        f.write('        /// 10 shield, 11 ranged), weapon type (2 bow, 4 sword, 5 staff; 0 otherwise), key (armor type for armor,\n')
        f.write('        /// material for weapons, 0 for necklaces, belts, rings and shields), level, base name and sell price.\n')
        f.write('        /// </summary>\n')
        f.write('        public static readonly (int equip, int weapon, int key, int level, string name, float sell)[] Pieces =\n        {\n')
        for p in pieces:
            f.write(f'            ({p[0]}, {p[1]}, {p[2]}, {p[3]}, "{p[4]}", {p[5]}f),\n')
        f.write('        };\n    }\n}\n')
    print(f'{len(pieces)} pieces')


if __name__ == '__main__':
    main(sys.argv[1])
